import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const scriptPath = fileURLToPath(import.meta.url);
const packageRoot = path.resolve(path.dirname(scriptPath), "..");
const sourcePath = path.join(packageRoot, "selection.json");
const outputPath = path.join(packageRoot, "src", "icon-data.ts");

const raw = await readFile(sourcePath, "utf8");
const selection = JSON.parse(raw);

if (!selection || !Array.isArray(selection.icons)) {
  throw new Error("Invalid IcoMoon selection.json file.");
}

function expandNames(rawName) {
  if (typeof rawName !== "string") {
    return [];
  }

  return rawName
    .split(",")
    .map((name) => name.trim())
    .filter(Boolean);
}

const iconEntries = selection.icons.map((entry) => {
  const aliases = expandNames(entry?.properties?.name);
  if (aliases.length === 0) {
    throw new Error(`Missing icon name for code ${entry?.properties?.code ?? "unknown"}.`);
  }

  return {
    aliases,
    code: entry.properties.code,
    pathCount: Array.isArray(entry.icon?.paths) ? entry.icon.paths.length : 0
  };
});

const names = iconEntries.flatMap((entry) => entry.aliases);
const uniqueNames = new Set(names);
if (uniqueNames.size !== names.length) {
  throw new Error("Duplicate icon names detected in selection.json.");
}

const lines = [];
lines.push("/* eslint-disable */");
lines.push("// This file is generated by scripts/generate-icon-data.mjs.");
lines.push("// Do not edit by hand.");
lines.push("");
lines.push("export const iconNames = [");
for (const name of names) {
  lines.push(`  ${JSON.stringify(name)},`);
}
lines.push("] as const;");
lines.push("");
lines.push("export type IconName = (typeof iconNames)[number];");
lines.push("");
lines.push(`export const iconGlyphCount = ${selection.icons.length};`);
lines.push("");
lines.push("export const iconCount = iconNames.length;");
lines.push("");
lines.push("export interface IconDefinition {");
lines.push("  code: number;");
lines.push("  pathCount: number;");
lines.push("  aliases: readonly string[];");
lines.push("}");
lines.push("");
lines.push("export const iconDefinitions: Record<IconName, IconDefinition> = {");

for (const entry of iconEntries) {
  for (const name of entry.aliases) {
    lines.push(`  ${JSON.stringify(name)}: {`);
    lines.push(`    code: ${entry.code},`);
    lines.push(`    pathCount: ${entry.pathCount},`);
    lines.push(`    aliases: ${JSON.stringify(entry.aliases)},`);
    lines.push("  },");
  }
}

lines.push("};");
lines.push("");

await writeFile(outputPath, `${lines.join("\n")}\n`);
